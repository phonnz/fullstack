  @doc ~S"""
  Renders a table with generic styling.

  ## Examples

      <.table id="users" rows={@users}>
        <:col :let={user} label="id"><%= user.id %></:col>
        <:col :let={user} label="username"><%= user.username %></:col>
      </.table>
  """
  attr :id, :string, required: true
  attr :rows, :list, required: true
  attr :row_id, :any, default: nil, doc: "the function for generating the row id"
  attr :row_click, :any, default: nil, doc: "the function for handling phx-click on each row"

  attr :row_label, :any,
    default: nil,
    doc:
      "a function returning the accessible name for a clickable row, for example " <>
        "`fn url -> \"View \#{url.origin}\" end`. Without it a clickable row is " <>
        "announced only by its cell contents."

  attr :row_item, :any,
    default: &Function.identity/1,
    doc: "the function for mapping each row before calling the :col and :action slots"

  slot :col, required: true do
    attr :label, :string
  end

  slot :action, doc: "the slot for showing user actions in the last table column"

  def table(assigns) do
    assigns =
      with %{rows: %Phoenix.LiveView.LiveStream{}} <- assigns do
        assign(assigns, row_id: assigns.row_id || fn {id, _item} -> id end)
      end

    ~H"""
    <div class="overflow-y-auto px-4 sm:overflow-visible sm:px-0">
      <table class="w-[40rem] mt-11 sm:w-full">
        <thead class="text-sm text-left leading-6 text-muted">
          <tr>
            <th :for={col <- @col} class="p-0 pr-6 pb-4 font-normal">{col[:label]}</th>
            <th class="relative p-0 pb-4"><span class="sr-only">{gettext("Actions")}</span></th>
          </tr>
        </thead>
        <tbody
          id={@id}
          phx-update={match?(%Phoenix.LiveView.LiveStream{}, @rows) && "stream"}
          class="relative divide-y divide-base-300 border-t border-base-300 text-sm leading-6 text-base-content"
        >
          <tr
            :for={row <- @rows}
            id={@row_id && @row_id.(row)}
            tabindex={@row_click && "0"}
            role={@row_click && "button"}
            aria-label={@row_click && @row_label && @row_label.(@row_item.(row))}
            phx-click={@row_click && @row_click.(row)}
            phx-keydown={@row_click && @row_click.(row)}
            phx-key="Enter"
            class={[
              "group",
              @row_click && "hover:bg-base-200 hover:cursor-pointer",
              @row_click &&
                "focus-visible:outline focus-visible:outline-2 focus-visible:-outline-offset-2 focus-visible:outline-primary"
            ]}
          >
            <td :for={{col, i} <- Enum.with_index(@col)} class="relative p-0">
              <div class="block py-4 pr-6">
                <span class={["relative", i == 0 && "font-semibold text-base-content"]}>
                  {render_slot(col, @row_item.(row))}
                </span>
              </div>
            </td>
            <td :if={@action != []} class="relative w-14 p-0">
              <div class="relative whitespace-nowrap py-4 text-right text-sm font-medium">
                <span
                  :for={action <- @action}
                  class="relative ml-4 font-semibold leading-6 text-primary hover:underline"
                >
                  {render_slot(action, @row_item.(row))}
                </span>
              </div>
            </td>
          </tr>
        </tbody>
      </table>
    </div>
    """
  end

